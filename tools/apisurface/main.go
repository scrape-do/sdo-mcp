// Command apisurface prints sdo-mcp's compatibility surface — every command
// and flag, and every MCP tool and its input parameters — one symbol per
// line, sorted:
//
//	install sdo-mcp github.com/scrape-do/sdo-mcp/cmd/sdo-mcp
//	command sdo-mcp.serve
//	flag sdo-mcp.serve --token-file string
//	mcp-tool scrape
//	mcp-param scrape url string [required]
//
// No help prose and no versions: wording and releases are not API. A line that
// disappears is a breaking change; a new "[required]" line on an existing tool
// is one too. sdo-cli's tools/apisurface does the same for the CLI. Regenerate
// the golden with:
//
//	go run ./tools/apisurface > api-surface.txt
package main

import (
	"context"
	"flag"
	"fmt"
	"path"
	"sort"
	"strings"

	"github.com/scrape-do/sdo-mcp/internal/cmdline"
	"github.com/scrape-do/sdo-mcp/internal/mcp"
)

const header = "# sdo-mcp command-line + MCP compatibility surface. Generated by tools/apisurface -- DO NOT EDIT.\n" +
	"# Regenerate: go run ./tools/apisurface > api-surface.txt\n"

func main() {
	fmt.Print(render())
}

// installPath is the package `go install` builds the sdo-mcp binary from. Go
// names the binary after its last element, so it is part of the contract:
// moving it changes what users type and what their binary is called.
const installPath = "github.com/scrape-do/sdo-mcp/cmd/sdo-mcp"

func render() string {
	serve, _ := cmdline.NewServeFlags(nil)
	lines := append(commandLines(cmdline.Name, cmdline.Commands, map[string]*flag.FlagSet{"serve": serve}), mcpLines()...)
	lines = append(lines, "install "+path.Base(installPath)+" "+installPath)
	sort.Strings(lines)
	return header + strings.Join(lines, "\n") + "\n"
}

// commandLines lists the binary, its commands and each command's flags.
func commandLines(name string, commands []string, flags map[string]*flag.FlagSet) []string {
	lines := []string{"command " + name}
	for _, c := range commands {
		owner := name + "." + c
		lines = append(lines, "command "+owner)
		if fs := flags[c]; fs != nil {
			fs.VisitAll(func(f *flag.Flag) { lines = append(lines, flagLine(owner, f)) })
		}
	}
	return lines
}

func flagLine(owner string, f *flag.Flag) string {
	line := fmt.Sprintf("flag %s --%s %s", owner, f.Name, flagType(f))
	switch f.DefValue {
	case "", "false", "0":
	default:
		line += " default=" + f.DefValue
	}
	return line
}

// flagType names a flag's Go type (string, bool, float64, int64): every
// flag the flag package defines is a flag.Getter.
func flagType(f *flag.Flag) string {
	if g, ok := f.Value.(flag.Getter); ok {
		return fmt.Sprintf("%T", g.Get())
	}
	return "value"
}

// mcpLines reads the tool list the server actually serves.
func mcpLines() []string {
	resp := mcp.Handle(context.Background(), nil, &mcp.Request{JSONRPC: "2.0", ID: []byte("1"), Method: "tools/list"})
	var lines []string
	for _, tool := range resp.Result.(map[string]any)["tools"].([]map[string]any) {
		name := tool["name"].(string)
		lines = append(lines, "mcp-tool "+name)
		schema := tool["inputSchema"].(map[string]any)
		required := map[string]bool{}
		for _, r := range schema["required"].([]string) {
			required[r] = true
		}
		for param, def := range schema["properties"].(map[string]any) {
			d := def.(map[string]any)
			line := fmt.Sprintf("mcp-param %s %s %s", name, param, d["type"])
			if enum, ok := d["enum"].([]string); ok {
				line += " enum=" + strings.Join(enum, "|")
			}
			if required[param] {
				line += " [required]"
			}
			lines = append(lines, line)
		}
	}
	return lines
}
